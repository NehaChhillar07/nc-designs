// Builds the signature the homepage name is written with, from the Caveat
// handwriting face the site already uses. Each letter becomes its own path
// with a start time and duration (fractions of the whole signature, weighted
// by the letter's width), so the page can write it left to right at a pen's
// pace without any runtime font work.
//
//   npm i --no-save opentype.js@1.3.4
//   curl -L -o /tmp/Caveat.ttf "https://github.com/google/fonts/raw/main/ofl/caveat/Caveat%5Bwght%5D.ttf"
//   node scripts/build-signature.mjs /tmp/Caveat.ttf
//
// Writes components/home-v2/signature-paths.ts

import { writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
// OPENTYPE_FROM lets the library live outside the repo (e.g. a scratch install).
const require = createRequire(process.env.OPENTYPE_FROM ?? import.meta.url);
const opentype = require("opentype.js");

const fontPath = process.argv[2];
if (!fontPath) throw new Error("usage: node scripts/build-signature.mjs <Caveat.ttf>");
const font = opentype.loadSync(fontPath);

const SIZE = 100; // units: the viewBox is in these, so precision is plenty
const PAD = 6; // breathing room so loops and tails are never shaved
const SPACE_GAP = 0.08; // the pen lifts between words: a share of the total time

const round = (n) => Math.round(n * 10) / 10;

function build(text) {
    const glyphs = font.stringToGlyphs(text);
    const out = [];
    let x = 0;
    for (let i = 0; i < glyphs.length; i++) {
        const g = glyphs[i];
        const p = g.getPath(x, 0, SIZE);
        const bb = p.getBoundingBox();
        if (text[i] !== " " && Number.isFinite(bb.x1)) {
            out.push({ d: p.toPathData(1), x1: bb.x1, x2: bb.x2, y1: bb.y1, y2: bb.y2, space: false });
        } else {
            out.push({ space: true });
        }
        x += (g.advanceWidth / font.unitsPerEm) * SIZE;
        if (i < glyphs.length - 1) x += (font.getKerningValue(g, glyphs[i + 1]) / font.unitsPerEm) * SIZE;
    }

    const letters = out.filter((g) => !g.space);
    const minX = Math.min(...letters.map((g) => g.x1)) - PAD;
    const maxX = Math.max(...letters.map((g) => g.x2)) + PAD;
    const minY = Math.min(...letters.map((g) => g.y1)) - PAD;
    const maxY = Math.max(...letters.map((g) => g.y2)) + PAD;

    // Time is shared by width, so wide letters take longer, like a real pen.
    const spaces = out.filter((g) => g.space).length;
    const inkTime = 1 - spaces * SPACE_GAP;
    const totalW = letters.reduce((s, g) => s + (g.x2 - g.x1), 0);
    let t = 0;
    const timed = [];
    for (const g of out) {
        if (g.space) {
            t += SPACE_GAP;
            continue;
        }
        const dur = ((g.x2 - g.x1) / totalW) * inkTime;
        timed.push({
            d: g.d,
            // The wipe that reveals this letter: from its left edge to its right.
            x: round(g.x1 - 1),
            w: round(g.x2 - g.x1 + 2),
            at: Math.round(t * 1000) / 1000,
            dur: Math.round(dur * 1000) / 1000,
        });
        t += dur;
    }

    return {
        viewBox: [minX, minY, maxX - minX, maxY - minY].map(round).join(" "),
        // Where the baseline sits, as a share of the height (for aligning to type).
        baseline: Math.round((-minY / (maxY - minY)) * 1000) / 1000,
        glyphs: timed,
    };
}

const words = { neha: build("neha"), chhillar: build("chhillar"), full: build("neha chhillar") };

const ts = `// Generated by scripts/build-signature.mjs from Caveat. Do not edit by hand.
// Each glyph: its outline (d), the strip that reveals it (x, w), and when it
// is written (at, dur), as fractions of the whole signature.

export type SignatureWord = {
    viewBox: string;
    baseline: number;
    glyphs: { d: string; x: number; w: number; at: number; dur: number }[];
};

export const SIGNATURE = ${JSON.stringify(words, null, 4)} satisfies Record<string, SignatureWord>;
`;

const dest = path.join(root, "components/home-v2/signature-paths.ts");
await writeFile(dest, ts);
console.log(`wrote ${path.relative(root, dest)}`, Object.fromEntries(Object.entries(words).map(([k, v]) => [k, v.viewBox])));
